inline int ConsoleGameLanguage(int ps5) {
  switch (ps5) {
    case 0: return 2;
    case 2: case 22: return 4;
    case 3: case 20: return 5;
    case 4: return 3;
    case 5: return 6;
    case 7: case 17: return 9;
    default: return 1;
  }
}
